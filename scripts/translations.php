<?php

/** Standalone contributor tooling: no database or application boot is needed. */
final class TranslationCatalogs
{
    public function __construct(private readonly string $langPath) {}

    public function rows(string $locale): array
    {
        $this->validateLocale($locale);
        $rows = [];
        foreach (glob($this->langPath.'/en/*.php') ?: [] as $sourceFile) {
            $catalog = basename($sourceFile, '.php');
            $targetFile = $this->langPath.'/'.$locale.'/'.$catalog.'.php';
            $target = is_file($targetFile) ? require $targetFile : [];
            foreach ($this->flatten(require $sourceFile) as [$path, $english]) {
                $translation = $this->readPath($target, $path);
                $status = $translation === null ? 'missing'
                    : (trim($translation) === '' ? 'empty'
                        : ($translation === $english ? 'same_as_english' : 'translated'));
                if ($translation !== null && $this->placeholders($english) !== $this->placeholders($translation)) {
                    $status = 'invalid_tokens';
                }
                $rows[] = [$locale, $catalog, implode('.', $path), json_encode($path, JSON_UNESCAPED_UNICODE), $english, $translation ?? '', $status];
            }
        }

        return $rows;
    }

    public function export(string $locale, string $filename): void
    {
        $rows = $this->rows($locale);
        $stream = fopen($filename, 'wb');
        if (! $stream) {
            throw new RuntimeException('Cannot write export.');
        }
        fputcsv($stream, ['locale', 'catalog', 'key', 'path', 'english', 'translation', 'status'], ',', '"', '');
        foreach ($rows as $row) {
            // CSV quoting preserves real newlines, HTML, quotes and accents.
            fputcsv($stream, $row, ',', '"', '');
        }
        fclose($stream);
    }

    public function import(string $locale, string $filename): void
    {
        $this->validateLocale($locale);
        $expected = [];
        foreach ($this->rows($locale) as $row) {
            $expected[$row[1].':'.$row[3]] = $row;
        }
        $stream = fopen($filename, 'rb');
        if (! $stream) {
            throw new RuntimeException('Cannot read import.');
        }
        try {
            $header = fgetcsv($stream, 0, ',', '"', '');
            if (is_array($header)) {
                $header[0] = preg_replace('/^\xEF\xBB\xBF/', '', $header[0]);
            }
            if ($header !== ['locale', 'catalog', 'key', 'path', 'english', 'translation', 'status']) {
                throw new InvalidArgumentException('Use an export generated by this script.');
            }
            $catalogs = [];
            $seen = [];
            while (($row = fgetcsv($stream, 0, ',', '"', '')) !== false) {
                if (count($row) !== 7) {
                    throw new InvalidArgumentException('Invalid CSV row.');
                }
                [$rowLocale, $catalog, $key, $pathJson, $english, $translation] = $row;
                $identity = $catalog.':'.$pathJson;
                $source = $expected[$identity] ?? null;
                if ($rowLocale !== $locale || ! $source || $source[2] !== $key || $source[4] !== $english || isset($seen[$identity])) {
                    throw new InvalidArgumentException('Unknown, duplicated or outdated translation: '.$key);
                }
                $seen[$identity] = true;
                if (trim($translation) === '' || $translation === $source[5]) {
                    continue; // Keep the existing translation or English runtime fallback.
                }
                if ($this->tokens($english) !== $this->tokens($translation)) {
                    throw new InvalidArgumentException('Changed placeholders or HTML tags: '.$key);
                }
                if (! isset($catalogs[$catalog])) {
                    $targetFile = $this->langPath.'/'.$locale.'/'.$catalog.'.php';
                    $catalogs[$catalog] = is_file($targetFile) ? require $targetFile : [];
                }
                $target = &$catalogs[$catalog];
                foreach (json_decode($pathJson, true, 512, JSON_THROW_ON_ERROR) as $part) {
                    $target = &$target[$part];
                }
                $target = $translation;
                unset($target);
            }
        } finally {
            fclose($stream);
        }
        // Validate the whole input before writing any catalog. Literal dotted keys
        // and nested arrays retain their original structure.
        foreach ($catalogs as $catalog => $values) {
            $file = $this->langPath.'/'.$locale.'/'.$catalog.'.php';
            if (file_put_contents($file, "<?php\n\nreturn ".var_export($values, true).";\n") === false) {
                throw new RuntimeException('Cannot write catalog: '.$catalog);
            }
        }
    }

    private function validateLocale(string $locale): void
    {
        if (! preg_match('/^[A-Za-z][A-Za-z0-9_]*$/D', $locale) || ! is_dir($this->langPath.'/'.$locale)) {
            throw new InvalidArgumentException('Unknown locale.');
        }
    }

    private function flatten(array $values, array $prefix = []): array
    {
        $rows = [];
        foreach ($values as $key => $value) {
            $path = [...$prefix, $key];
            if (is_array($value)) {
                array_push($rows, ...$this->flatten($value, $path));
            } else {
                $rows[] = [$path, $value];
            }
        }

        return $rows;
    }

    private function readPath(array $values, array $path): ?string
    {
        $value = $values;
        foreach ($path as $part) {
            if (! is_array($value) || ! array_key_exists($part, $value)) {
                return null;
            }
            $value = $value[$part];
        }

        return is_string($value) ? $value : null;
    }

    private function tokens(string $value): array
    {
        $placeholders = $this->placeholders($value);
        preg_match_all('/<\/?[a-z][^>]*>/i', $value, $tags);

        return [$placeholders, array_map(fn ($tag) => preg_replace('/\balt="[^"]*"/i', 'alt=""', $tag), $tags[0])];
    }

    private function placeholders(string $value): array
    {
        preg_match_all('/(?<![A-Za-z0-9_]):[A-Za-z][A-Za-z0-9_]*/', $value, $matches);
        $placeholders = $matches[0];
        sort($placeholders);

        return $placeholders;
    }
}

if (PHP_SAPI === 'cli' && realpath($_SERVER['SCRIPT_FILENAME'] ?? '') === __FILE__) {
    try {
        $catalogs = new TranslationCatalogs(dirname(__DIR__).'/lang');
        $operation = $argv[1] ?? 'check';
        $locale = $argv[2] ?? null;
        if (in_array($operation, ['export', 'import'], true) && $locale && isset($argv[3])) {
            $catalogs->{$operation}($locale, $argv[3]);
            echo ucfirst($operation)." completed for {$locale}.\n";
        } elseif ($operation === 'check') {
            $failures = 0;
            $locales = $locale ? [$locale] : array_map('basename', glob(dirname(__DIR__).'/lang/*', GLOB_ONLYDIR) ?: []);
            foreach (array_diff($locales, ['vendor']) as $language) {
                foreach ($catalogs->rows($language) as $row) {
                    if (in_array($row[6], ['missing', 'empty', 'invalid_tokens'], true)) {
                        fwrite(STDERR, "{$language}/{$row[1]} {$row[2]}: {$row[6]}\n");
                        $failures++;
                    }
                }
            }
            echo "Translation check: {$failures} errors.\n";
            exit($failures ? 1 : 0);
        } else {
            throw new InvalidArgumentException('Usage: php scripts/translations.php check [locale] | export|import locale file.csv');
        }
    } catch (Throwable $exception) {
        fwrite(STDERR, $exception->getMessage()."\n");
        exit(1);
    }
}
